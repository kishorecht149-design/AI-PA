export function getEseItemById(id: string): EseChecklistItem | EsePartDMilestone | undefined {
  if (id.startsWith("ESE-PD-")) {
    return ESE_PART_D_MILESTONES.find((m) => m.id === id);
  }
  return ESE_CHECKLIST_ITEMS.find((item) => item.id === id);
}

export function searchEseSyllabus(query: string) {
  const q = query.toLowerCase().trim();
  if (!q) return ESE_CHECKLIST_ITEMS;
  return ESE_CHECKLIST_ITEMS.filter(
    (item) =>
      item.subtopicTitle.toLowerCase().includes(q) ||
      item.chapterTitle.toLowerCase().includes(q) ||
      item.subjectTitle.toLowerCase().includes(q) ||
      item.id.toLowerCase().includes(q)
  );
}
